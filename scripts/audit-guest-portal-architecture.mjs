import fs from 'fs';
import path from 'path';
import process from 'process';

const repoRoot = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const guestRoot = path.join(repoRoot, 'apps/guest-portal');
const outputPath = path.join(repoRoot, 'docs/guest-portal-architecture-truth.md');

const ignoredDirs = new Set(['.next', 'node_modules', 'coverage']);
const runtimeRoots = ['app', 'components', 'hooks', 'lib', 'store'];
const staleScriptPatterns = [
  /firebase-admin/,
  /serviceAccount/,
  /Downloads\//,
  /lib\/server/,
];
const forbiddenRuntimePatterns = [
  /firebase-admin/,
  /firebase\/auth/,
  /firebase\/firestore/,
  /firebase\/storage/,
  /from\s+["'][^"']*lib\/server/,
  /from\s+["'][^"']*lib\/firebase/,
  /require\(["'][^"']*lib\/server/,
  /require\(["'][^"']*lib\/firebase/,
  /\buse server\b/,
];

function toPosix(filePath) {
  return filePath.split(path.sep).join('/');
}

function relative(filePath) {
  return toPosix(path.relative(repoRoot, filePath));
}

function walk(dir, visitor) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory() && ignoredDirs.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);
    visitor(fullPath, entry);
    if (entry.isDirectory()) walk(fullPath, visitor);
  }
}

function read(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function collect() {
  const runtimeFiles = [];
  const routeHandlers = [];
  const duplicateArtifacts = [];
  const emptyDirs = [];
  const forbiddenRuntimeMatches = [];
  const staleScripts = [];
  const directApiFetches = [];
  const largeFiles = [];

  for (const rootName of runtimeRoots) {
    walk(path.join(guestRoot, rootName), (fullPath, entry) => {
      if (entry.isDirectory()) return;
      if (!/\.(js|jsx|ts|tsx)$/.test(entry.name)) return;
      runtimeFiles.push(relative(fullPath));
    });
  }

  walk(path.join(guestRoot, 'app/api'), (fullPath, entry) => {
    if (entry.isFile() && /^route\.(js|jsx|ts|tsx)$/.test(entry.name)) {
      routeHandlers.push(relative(fullPath));
    }
  });

  walk(guestRoot, (fullPath, entry) => {
    if (entry.isFile() && /(?: 2\.[jt]sx?| copy\.[jt]sx?|\.bak|\.old)$/.test(entry.name)) {
      duplicateArtifacts.push(relative(fullPath));
    }
    if (entry.isDirectory()) {
      const entries = fs.readdirSync(fullPath);
      if (entries.length === 0) emptyDirs.push(relative(fullPath));
    }
  });

  for (const runtimeFile of runtimeFiles) {
    const fullPath = path.join(repoRoot, runtimeFile);
    const source = read(fullPath);
    const lines = source.split('\n').length;
    if (lines >= 700) largeFiles.push({ file: runtimeFile, lines });
    for (const pattern of forbiddenRuntimePatterns) {
      if (pattern.test(source)) {
        forbiddenRuntimeMatches.push({ file: runtimeFile, pattern: String(pattern) });
      }
      pattern.lastIndex = 0;
    }
    if (/fetch\(\s*[`"']\/api\/v1/.test(source)) {
      directApiFetches.push(runtimeFile);
    }
  }

  walk(path.join(guestRoot, 'scripts'), (fullPath, entry) => {
    if (!entry.isFile() || !/\.(js|mjs|cjs|ts)$/.test(entry.name)) return;
    const source = read(fullPath);
    const matches = staleScriptPatterns.filter((pattern) => pattern.test(source)).map(String);
    if (matches.length > 0) staleScripts.push({ file: relative(fullPath), matches });
  });

  return {
    generatedAt: new Date().toISOString(),
    runtimeFiles: runtimeFiles.sort(),
    routeHandlers: routeHandlers.sort(),
    duplicateArtifacts: duplicateArtifacts.sort(),
    emptyDirs: emptyDirs.sort(),
    forbiddenRuntimeMatches: forbiddenRuntimeMatches.sort((a, b) => a.file.localeCompare(b.file)),
    staleScripts: staleScripts.sort((a, b) => a.file.localeCompare(b.file)),
    directApiFetches: [...new Set(directApiFetches)].sort(),
    largeFiles: largeFiles.sort((a, b) => b.lines - a.lines),
  };
}

function list(values, fallback = '- None.') {
  if (!values.length) return fallback;
  return values.map((value) => `- ${typeof value === 'string' ? value : JSON.stringify(value)}`).join('\n');
}

function render(report) {
  return `# Guest Portal Architecture Truth Report

Generated by \`node scripts/audit-guest-portal-architecture.mjs --write\`.

## Summary

- Generated at: ${report.generatedAt}
- Runtime files scanned: ${report.runtimeFiles.length}
- Guest Portal app/api route handlers: ${report.routeHandlers.length}
- Duplicate or backup artifacts: ${report.duplicateArtifacts.length}
- Empty source directories: ${report.emptyDirs.length}
- Forbidden runtime pattern matches: ${report.forbiddenRuntimeMatches.length}
- Direct browser \`/api/v1\` fetch sites: ${report.directApiFetches.length}
- Stale script/tooling files: ${report.staleScripts.length}

## Route Handlers

${list(report.routeHandlers)}

## Duplicate Or Backup Artifacts

${list(report.duplicateArtifacts)}

## Empty Directories

${list(report.emptyDirs)}

## Forbidden Runtime Matches

${list(report.forbiddenRuntimeMatches)}

## Direct Browser API Fetch Sites

${list(report.directApiFetches)}

## Stale Script And Tooling Debt

${list(report.staleScripts)}

## Large Runtime Files

${list(report.largeFiles.map((entry) => `${entry.file} (${entry.lines} lines)`))}
`;
}

const report = collect();
const markdown = render(report);

if (process.argv.includes('--json')) {
  console.log(JSON.stringify(report, null, 2));
} else if (process.argv.includes('--write')) {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, markdown);
  console.log(`Wrote ${relative(outputPath)}`);
} else if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath)) {
    console.error(`${relative(outputPath)} is missing. Run with --write.`);
    process.exitCode = 1;
  } else {
    const current = read(outputPath).replace(/Generated at: .+/g, 'Generated at: <timestamp>');
    const next = markdown.replace(/Generated at: .+/g, 'Generated at: <timestamp>');
    if (current !== next) {
      console.error(`${relative(outputPath)} is stale. Run with --write.`);
      process.exitCode = 1;
    } else {
      console.log(`${relative(outputPath)} is current.`);
    }
  }
} else {
  console.log(markdown);
}
